"""Build the real pipeline workspace from the team's uploaded captures.

`python -m atlas real-ingest` registers every file listed in the uploaded
`manifest.jsonl` as a recorded capture (target URL, fetch time, status and
SHA-256 are verified against the manifest), then runs the source loaders
offline. Everything produced is *pending*: the disease selection, research
contexts, audit rows, mechanism subgroups and community records are drafts
derived from source records, and none of them is public until a person
accepts it through `review-export`/`review-batch`/`review-import`.

Selection rules (deterministic, source-justified, no memory or keywords):
- genes: the `genes` and `stretch_genes` of the uploaded run config, resolved
  through their HGNC records;
- diseases: Mondo IDs that GenCC associates with those genes with a
  classification other than the non-positive vocabulary, plus Orphanet
  associations with status `Assessed` and a `Disease-causing...` type mapped
  to exactly one Mondo ID by an exact SSSOM mapping, plus Mondo IDs named by a
  drafted community remit. Obsolete Mondo IDs resolve only through a single
  source-provided replacement;
- mechanism subgroups: only where Orphanet's controlled association type
  itself states loss or gain of function.
"""

